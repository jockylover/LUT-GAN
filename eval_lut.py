import argparse
import math
import os

import torch
from PIL import Image
from torchvision import transforms

from modules import (
    StyleEncoder,
    LUTGenerator,
    create_identity_lut,
    apply_lut_3d,
)
from preprocess import build_style_transform
from lut_io import load_cube, resample_lut


def parse_args():
    p = argparse.ArgumentParser(description="Evaluate predicted LUT against ground truth")
    p.add_argument("--ckpt", type=str, required=True, help="Path to checkpoint .pth")
    p.add_argument("--style", type=str, required=True, help="Path to style image")
    p.add_argument("--lut", type=str, required=True, help="Path to ground-truth LUT .cube")
    p.add_argument("--content", type=str, required=True, help="Path to content image")
    p.add_argument("--output_dir", type=str, default="outputs/eval_lut")
    p.add_argument("--image_size", type=int, default=256)
    p.add_argument("--device", type=str, default="cuda")
    return p.parse_args()


def load_style(path, image_size, style_norm):
    tfm = build_style_transform(image_size, style_norm)
    img = Image.open(path).convert("RGB")
    return tfm(img).unsqueeze(0)


def load_content(path):
    tfm = transforms.ToTensor()
    img = Image.open(path).convert("RGB")
    return tfm(img).unsqueeze(0)


def save_image(tensor, path):
    tensor = tensor.clamp(0, 1).squeeze(0)
    img = transforms.ToPILImage()(tensor.cpu())
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


def compute_psnr(a: torch.Tensor, b: torch.Tensor) -> float:
    mse = torch.mean((a - b) ** 2).item()
    if mse == 0:
        return float("inf")
    return 10.0 * math.log10(1.0 / mse)


def save_cube_lut(lut: torch.Tensor, path: str):
    N = lut.shape[0]
    lut_np = lut.detach().cpu().numpy().reshape(-1, 3)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("# Generated by LUT-GAN\n")
        f.write("LUT_3D_SIZE {}\n".format(N))
        for r, g, b in lut_np:
            f.write(f"{r:.6f} {g:.6f} {b:.6f}\n")


def main():
    args = parse_args()
    device = args.device if torch.cuda.is_available() else "cpu"

    ckpt = torch.load(args.ckpt, map_location=device)
    ckpt_args = ckpt["args"]
    lut_size = ckpt_args["lut_size"]
    latent_dim = ckpt_args["latent_dim"]
    encoder_arch = ckpt_args.get("encoder_arch", "resnet18")
    delta_scale = ckpt_args.get("delta_scale", 0.1)
    zero_mean = ckpt_args.get("zero_mean", True)
    style_norm = ckpt_args.get("style_norm", "none")

    identity_lut = create_identity_lut(lut_size, device=device)

    encoder = StyleEncoder(latent_dim=latent_dim, arch=encoder_arch)
    generator = LUTGenerator(latent_dim=latent_dim, size=lut_size, delta_scale=delta_scale, zero_mean=zero_mean)

    encoder.load_state_dict(ckpt["encoder"])
    generator.load_state_dict(ckpt["generator"])

    encoder.to(device).eval()
    generator.to(device).eval()

    style_img = load_style(args.style, args.image_size, style_norm).to(device)
    content_img = load_content(args.content).to(device)

    with torch.no_grad():
        z = encoder(style_img)
        lut_pred = generator(z, identity_lut)[0]  # [N,N,N,3]

    lut_gt = load_cube(args.lut)
    lut_gt = resample_lut(lut_gt, lut_size).to(device)

    lut_l1 = (lut_pred - lut_gt).abs().mean().item()
    lut_max = (lut_pred - lut_gt).abs().max().item()

    with torch.no_grad():
        pred_out = apply_lut_3d(content_img, lut_pred.unsqueeze(0))
        gt_out = apply_lut_3d(content_img, lut_gt.unsqueeze(0))

    out_l1 = (pred_out - gt_out).abs().mean().item()
    out_psnr = compute_psnr(pred_out, gt_out)

    os.makedirs(args.output_dir, exist_ok=True)
    save_image(pred_out, os.path.join(args.output_dir, "pred_output.png"))
    save_image(gt_out, os.path.join(args.output_dir, "gt_output.png"))
    save_cube_lut(lut_pred, os.path.join(args.output_dir, "pred_lut.cube"))

    print(f"LUT L1: {lut_l1:.6f}")
    print(f"LUT max abs: {lut_max:.6f}")
    print(f"Output L1: {out_l1:.6f}")
    print(f"Output PSNR: {out_psnr:.2f} dB")
    print("Saved outputs to", args.output_dir)


if __name__ == "__main__":
    main()
